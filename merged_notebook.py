for p in student_hard.parameters(): p.requires_grad = False
for p in student_hard.head.parameters(): p.requires_grad = True
for p in student_hard.head_dist.parameters(): p.requires_grad = True

# 4. Training (1 Epoch per student)
def fast_kd_train(student, mode="soft", T_temp=4.0, alpha=0.7):
    opt = torch.optim.AdamW([p for p in student.parameters() if p.requires_grad], lr=2e-3)
    student.train()
    for x, y in train_loader:
        with torch.no_grad():
            t_logits = teacher(x)
        s_out = student(x)

        if mode == "soft":
            loss = (1 - alpha) * F.cross_entropy(s_out, y) + alpha * (T_temp ** 2) * F.kl_div(
                F.log_softmax(s_out / T_temp, dim=-1),
                F.softmax(t_logits / T_temp, dim=-1),
                reduction="batchmean"
            )
        else: # Hard
            cls_out = s_out[0] if isinstance(s_out, (tuple, list)) else s_out
            dist_out = s_out[1] if isinstance(s_out, (tuple, list)) and len(s_out) == 2 else s_out
            loss = 0.5 * F.cross_entropy(cls_out, y) + 0.5 * F.cross_entropy(dist_out, t_logits.argmax(-1))

        opt.zero_grad()
        loss.backward()
        opt.step()

fast_kd_train(student_soft, mode="soft")
fast_kd_train(student_hard, mode="hard")

# 5. Fast Evaluation & Profiling
def eval_profile(model, name, is_dist=False):
    model.eval()
    correct, total = 0, 0
    with torch.no_grad():
        for x, y in test_loader:
            out = model(x)
            logits = (out[0] + out[1]) / 2 if is_dist and isinstance(out, (tuple, list)) and len(out) == 2 else (out[0] if isinstance(out, (tuple, list)) else out)
            correct += logits.argmax(-1).eq(y).sum().item()
            total += y.size(0)

    dummy = torch.randn(1, 3, 224, 224)
    flops, params = profile(model, inputs=(dummy,), verbose=False)

    t0 = time.time()
    with torch.no_grad():
        for _ in range(3): _ = model(dummy)
    latency = ((time.time() - t0) / 3) * 1000
    acc = (correct / total) * 100

    print(f"{name:<18} | Params: {params/1e6:5.2f}M | FLOPs: {flops/1e9:5.2f}G | Latency: {latency:5.1f}ms | Acc: {acc:.2f}%")
    return params / 1e6, acc

